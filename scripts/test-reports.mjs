import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const code=ts.transpileModule(readFileSync('lib/reports.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {reportFilters,filterReport,reportDay,reportCsv}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const fixture=[{id:'abc-1',title:'=HYPERLINK("x")',category:'Cadastro',name:'João; "Silva"',email:'joao@example.test',status:'Aprovado',revision:2,created:'2026-10-24T01:00:00Z',updated:'2026-10-24T05:00:00Z'},{id:'abc-2',title:'Recibo',category:'Reembolso',name:'Ana',email:'ana@example.test',status:'Em análise',revision:1,created:'2026-10-24T10:00:00Z',updated:'2026-10-24T10:00:00Z'}];
const filter=query=>filterReport(fixture,reportFilters(new URLSearchParams(query)));
assert.equal(reportDay(fixture[0].created),'2026-10-23');
assert.equal(filter('from=2026-10-23&to=2026-10-23&status=Aprovado&category=Cadastro&q=JOÃO').length,1);
assert.equal(filter('from=2026-10-24&to=2026-10-24')[0].id,'abc-2');
assert.equal(filter('q=ana%40example.test').length,1);
assert.equal(filter('q=%23ABC-1').length,1);
assert.throws(()=>reportFilters(new URLSearchParams('from=2026-02-30')));
assert.throws(()=>reportFilters(new URLSearchParams('from=2026-99-99')));
assert.throws(()=>reportFilters(new URLSearchParams('from=2026-10-24&to=2026-10-23')));
const csv=reportCsv(fixture);assert.ok(csv.startsWith('\uFEFF'));assert.ok(csv.includes('"\'=HYPERLINK(""x"")"'));assert.ok(csv.includes('"João; ""Silva"""'));assert.ok(csv.includes('23/10/2026'));assert.ok(csv.endsWith('\r\n'));
for(const prefix of ['=','+','-','@','\t=','\r\n+','  @'])assert.ok(reportCsv([{...fixture[0],title:prefix+'formula'}]).includes('"\''+prefix));
assert.equal(reportCsv([]).trim().split('\r\n').length,1);
console.log('✓ Report filters, Brasília date boundaries, CSV accents, escaping and formula neutralization');
